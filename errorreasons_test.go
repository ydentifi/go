package ydentifi

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"testing"

	identitypb "github.com/ydentifi/go/internal/ydfi-proto-go/identity"
)

// TestErrorReasonsAreExported checks that errorreasons.go contains one
// constant per protocol reason. YDFI_UPDATE_REASONS=1 regenerates the file.
func TestErrorReasonsAreExported(t *testing.T) {
	numbers := make([]int, 0, len(identitypb.ErrorReason_name))
	for n := range identitypb.ErrorReason_name {
		numbers = append(numbers, int(n))
	}
	sort.Ints(numbers)

	var b bytes.Buffer
	b.WriteString(`// Code generated by TestErrorReasonsAreExported; DO NOT EDIT.

package ydentifi

import "strconv"

// ErrorReason is the server's domain reason for an error, carried by
// StatusError.Reason. Unknown reasons retain their numeric value.
type ErrorReason int32

// ErrorReason constants identify protocol error reasons. The README lists
// the reasons returned by each operation.
const (
`)
	for _, n := range numbers {
		fmt.Fprintf(&b, "\t%s ErrorReason = %d\n", reasonConstName(identitypb.ErrorReason_name[int32(n)]), n)
	}
	b.WriteString(`)

var errorReasonNames = map[ErrorReason]string{
`)
	for _, n := range numbers {
		fmt.Fprintf(&b, "\t%s: %q,\n", reasonConstName(identitypb.ErrorReason_name[int32(n)]), reasonName(identitypb.ErrorReason_name[int32(n)]))
	}
	b.WriteString(`}

// String returns the reason's name, such as "USER_NOT_FOUND", or
// "UNKNOWN_<n>" for a reason newer than this SDK.
func (r ErrorReason) String() string {
	if name, ok := errorReasonNames[r]; ok {
		return name
	}
	return "UNKNOWN_" + strconv.Itoa(int(r))
}
`)
	want, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}

	got, err := os.ReadFile("errorreasons.go")
	if os.Getenv("YDFI_UPDATE_REASONS") == "1" {
		if err := os.WriteFile("errorreasons.go", want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if err != nil || !bytes.Equal(got, want) {
		t.Fatalf("errorreasons.go is not the protocol's reasons (YDFI_UPDATE_REASONS=1 rewrites it): %v", err)
	}
}

// reasonName is a proto reason's name without the enum's prefix:
// ERROR_REASON_UNSPECIFIED → UNSPECIFIED, as the other enums name theirs.
func reasonName(proto string) string {
	return strings.TrimPrefix(proto, "ERROR_REASON_")
}

// reasonConstName is the Go name for a proto reason: USER_NOT_FOUND →
// ErrorReasonUserNotFound, ERROR_REASON_UNSPECIFIED → ErrorReasonUnspecified,
// with Go's initialisms: TOTP_LOCKED → ErrorReasonTOTPLocked.
func reasonConstName(proto string) string {
	var b strings.Builder
	b.WriteString("ErrorReason")
	for _, word := range strings.Split(reasonName(proto), "_") {
		switch {
		case word == "":
		case initialisms[word]:
			b.WriteString(word)
		default:
			b.WriteString(word[:1])
			b.WriteString(strings.ToLower(word[1:]))
		}
	}
	return b.String()
}

// initialisms are the words in reason names that Go spells in capitals.
var initialisms = map[string]bool{"TOTP": true, "MTLS": true, "ID": true, "URL": true}

func TestReasonConstName(t *testing.T) {
	for in, want := range map[string]string{
		"ERROR_REASON_UNSPECIFIED": "ErrorReasonUnspecified",
		"USER_NOT_FOUND":           "ErrorReasonUserNotFound",
		"TOTP_LOCKED":              "ErrorReasonTOTPLocked",
		"MTLS_CERT_EXPIRED":        "ErrorReasonMTLSCertExpired",
		"MAX_DEVICES_REACHED":      "ErrorReasonMaxDevicesReached",
	} {
		if got := reasonConstName(in); got != want {
			t.Errorf("reasonConstName(%s) = %s, want %s", in, got, want)
		}
	}
}
